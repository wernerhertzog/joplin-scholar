'use strict';
const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const root = path.resolve(__dirname, '..');
const dist = path.join(root, 'dist');
const publish = path.join(root, 'publish');
fs.mkdirSync(dist, { recursive: true });
fs.mkdirSync(publish, { recursive: true });
(async () => {
  const stylesDir = path.join(root, 'src/styles');
  const styles = Object.fromEntries(fs.readdirSync(stylesDir).filter(name => name.endsWith('.csl')).sort().map(name => [name.slice(0, -4), fs.readFileSync(path.join(stylesDir, name), 'utf8')]));
  fs.writeFileSync(path.join(stylesDir, 'styles.json'), JSON.stringify(styles));
  await esbuild.build({ entryPoints: [path.join(root, 'src/index.js')], bundle: true, platform: 'node', target: 'node18', outfile: path.join(dist, 'index.js') });
  for (const name of ['worker', 'panel']) await esbuild.build({ entryPoints: [path.join(root, `src/${name}.js`)], bundle: true, platform: 'browser', format: 'iife', target: 'chrome120', outfile: path.join(dist, `${name}.js`) });
  for (const name of ['manifest.json', 'panel.css']) fs.copyFileSync(path.join(root, 'src', name), path.join(dist, name));
  // Reuse the actual logo's geometry as a monochrome, theme-coloured mask.
  const logo = fs.readFileSync(path.join(root, 'assets/joplin-scholar-logo.svg'), 'utf8');
  const shapes = (logo.match(/<path\b[^>]*\/>/g) || []).join('').replace(/fill="#fff"/g, 'fill="black"');
  if (!shapes) throw new Error('The Scholar logo has no paths for its toolbar icon.');
  const mask = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><mask id="cutout"><rect width="512" height="512" fill="white"/>${shapes}</mask><rect width="512" height="512" rx="105" fill="white" mask="url(#cutout)"/></svg>`;
  const image = `data:image/svg+xml;base64,${Buffer.from(mask).toString('base64')}`;
  fs.writeFileSync(path.join(dist, 'toolbar.css'), `.toolbar-icon.scholar-toolbar-icon { display: inline-block; width: 16px; height: 16px; background-color: currentColor; -webkit-mask: url("${image}") center / contain no-repeat; mask: url("${image}") center / contain no-repeat; }\n.toolbar-icon.scholar-toolbar-icon::before { content: none !important; }\n`);
  for (const name of ['joplin-scholar-example.md', 'example-workflow.png']) fs.copyFileSync(path.join(root, 'examples', name), path.join(dist, name));
  fs.mkdirSync(path.join(dist, 'assets'), {recursive:true});
  for (const size of [16, 32, 48, 128]) fs.copyFileSync(path.join(root, 'assets', `icon-${size}.png`), path.join(dist, 'assets', `icon-${size}.png`));
  fs.copyFileSync(path.join(root, 'src/manifest.json'), path.join(publish, 'joplin-scholar.json'));
  fs.copyFileSync(path.join(root, 'LICENSE'), path.join(dist, 'LICENSE'));
  fs.copyFileSync(path.join(root, 'node_modules/pdfjs-dist/LICENSE'), path.join(dist, 'PDFJS-LICENSE'));
  fs.copyFileSync(path.join(root, 'node_modules/yaml/LICENSE'), path.join(dist, 'YAML-LICENSE'));
  fs.copyFileSync(path.join(root, 'src/styles/LICENSE.txt'), path.join(dist, 'CSL-STYLES-LICENSE.txt'));
  const archive = path.join(publish, 'joplin-scholar.jpl');
  fs.rmSync(archive, { force: true });
  execFileSync('tar', ['-cf', archive, 'index.js', 'manifest.json', 'panel.css', 'toolbar.css', 'panel.js', 'worker.js', 'joplin-scholar-example.md', 'example-workflow.png', 'assets/icon-16.png', 'assets/icon-32.png', 'assets/icon-48.png', 'assets/icon-128.png', 'LICENSE', 'PDFJS-LICENSE', 'YAML-LICENSE', 'CSL-STYLES-LICENSE.txt'], { cwd: dist, env: { ...process.env, COPYFILE_DISABLE: '1' } });
  console.log(`Built ${archive}`);
})().catch(error => { console.error(error); process.exitCode = 1; });
